#!/usr/bin/env python3
"""Halve the wallpapers to save flash: main/assets/img_wall_*.c from 320x240
RGB565 (154 KB each, as tools/gen_wallpaper.py writes them) to 160x120 RGB888
(58 KB). Each new pixel is the mean of four, which also undoes the generator's
dither. The firmware scales them back up once, in RAM (ui_wallpaper() in
main/core/ui_theme.c). Run it after gen_wallpaper.py; it skips files that are
already halved.

usage: python3 tools/wall_half.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
for path in sorted(glob.glob(os.path.join(ROOT, "main", "assets", "img_wall_*.c"))):
    src = open(path).read()
    name = re.search(r"const lv_image_dsc_t (\w+)", src).group(1)
    w, h = map(int, re.search(r"\.w = (\d+), \.h = (\d+)", src).groups())
    if "RGB565" not in src or (w, h) != (320, 240):
        print(f"{os.path.basename(path)}: already {w}x{h}, skipped")
        continue
    raw = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", src.split("_map[] = {")[1].split("};")[0]))

    def rgb(x, y):
        v = raw[(y * w + x) * 2] | raw[(y * w + x) * 2 + 1] << 8
        r, g, b = v >> 11, (v >> 5) & 63, v & 31
        return (r << 3 | r >> 2, g << 2 | g >> 4, b << 3 | b >> 2)

    out = bytearray()
    for y in range(0, h, 2):
        for x in range(0, w, 2):
            four = [rgb(x, y), rgb(x + 1, y), rgb(x, y + 1), rgb(x + 1, y + 1)]
            r, g, b = (round(sum(p[i] for p in four) / 4) for i in range(3))
            out += bytes((b, g, r))     # LVGL's RGB888 is blue first
    with open(path, "w") as f:
        f.write("// Generated by tools/gen_wallpaper.py, halved by tools/wall_half.py. Do not edit.\n")
        f.write('#include "lvgl.h"\n\n')
        f.write(f"static const uint8_t {name}_map[] = {{\n")
        for i in range(0, len(out), 24):
            f.write("    " + ", ".join(f"0x{v:02x}" for v in out[i:i + 24]) + ",\n")
        f.write("};\n\n")
        f.write(f"const lv_image_dsc_t {name} = {{\n"
                f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB888,\n"
                f"                .w = {w // 2}, .h = {h // 2}, .stride = {w // 2 * 3} }},\n"
                f"    .data_size = sizeof({name}_map),\n"
                f"    .data = {name}_map,\n}};\n")
    print(f"{os.path.basename(path)}: {w // 2}x{h // 2} RGB888")
